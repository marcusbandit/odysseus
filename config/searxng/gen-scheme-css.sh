#!/usr/bin/env bash
# Generate custom/scheme.css (Material 3 colour tokens as CSS variables) from
# the live caelestia colour scheme, so SearXNG follows the desktop theme.
#
# The custom/ directory is bind mounted into the searxng container, and
# directory mounts propagate file changes live: no container restart needed,
# just a browser refresh.
#
# Wired to run automatically on scheme changes via the systemd user units
# searxng-caelestia-theme.{path,service}; also fine to run by hand.
set -euo pipefail

SCHEME_JSON="${1:-$HOME/.local/state/caelestia/scheme.json}"
OUT_DIR="$(dirname "$(realpath "$0")")/custom"
OUT="$OUT_DIR/scheme.css"

mkdir -p "$OUT_DIR"

python3 - "$SCHEME_JSON" "$OUT" <<'PY'
import json
import sys

with open(sys.argv[1], encoding="utf-8") as f:
    scheme = json.load(f)

mode = scheme.get("mode", "dark")
colours = scheme.get("colours", {})

lines = [
    "/* GENERATED by gen-scheme-css.sh from ~/.local/state/caelestia/scheme.json",
    f"   scheme: {scheme.get('name', '?')} / {scheme.get('flavour', '?')} / {mode}",
    "   Do not edit by hand; edits are overwritten on the next scheme change. */",
    ":root {",
    f"  color-scheme: {mode};",
]
for key, value in colours.items():
    lines.append(f"  --cael-{key}: #{value};")
lines.append("}")

with open(sys.argv[2], "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"wrote {sys.argv[2]} ({len(colours)} tokens, mode={mode})")
PY
